async function AccountNavigation() {
  // Read the signed cookie to determine whether someone is logged in.
  const session = await getSession();

  // if session returns true and the ObjectID _id is valid
  if (session && ObjectId.isValid(session.userId)) {
    // The header only needs the user's name, so no sensitive fields are loaded.
    // connect to database
    const db = await getDb();

    // get collection users from database
    // searches for the userId
    const user = await db.collection("users").findOne(
      // converts userId back into an ObjectId
      // finds which userId matches this value
      { _id: new ObjectId(session.userId) },

      // tells MongoDB which values to return, in this case just the name
      { projection: { _id: 0, name: 1 } },
    );

    // if user returns true and the user.name is a string
    if (user && typeof user.name === "string") {
      // return the users name and format it into a button for the header
      return (
        <Link
          href="/account"
          className="flex items-center gap-2 rounded-lg border border-border px-3.5 py-2 text-sm font-semibold text-foreground transition-colors hover:border-accent hover:text-accent"
          aria-label={`View ${user.name}'s account`}
        >
          <span className="flex h-6 w-6 items-center justify-center rounded-full bg-accent text-xs font-bold text-white">
            {user.name.charAt(0).toUpperCase()}
          </span>
          {user.name}
        </Link>
      );
    }
  }

  // Visitors without a valid account session see the authentication links.
  return (
    <>
      <Link
        href="/signup"
        className="rounded-lg border border-border px-3.5 py-2 text-sm font-semibold text-foreground transition-colors hover:border-accent hover:text-accent"
      >
        Sign up
      </Link>
      <Link
        href="/login"
        className="rounded-lg bg-accent px-3.5 py-2 text-sm font-semibold text-white transition hover:opacity-90"
      >
        Log in
      </Link>
    </>
  );
}

